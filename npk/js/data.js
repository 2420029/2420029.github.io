function btypeFromTitleText(html) {
  if (!html) return null;
  // 旧アーカイブは <TITLE>ピンサロ「店名」（地域）</TITLE> の形式で業種が入っている。
  const m = html.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
  if (!m) return null;
  const title = m[1];
  for (const [re, btype] of BODY2_BTYPE_MAP) {
    if (re.test(title)) return btype;
  }
  return null;
}

